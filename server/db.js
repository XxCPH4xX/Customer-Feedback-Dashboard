const { Pool } = require('pg');
const { attachDatabasePool } = require('@vercel/functions');

let pool;
let initialization;

function getPool() {
  if (!pool) {
    const connectionString = process.env.DATABASE_URL || process.env.POSTGRES_URL;
    if (!connectionString) {
      const error = new Error('Set DATABASE_URL or POSTGRES_URL to a PostgreSQL connection string');
      error.code = 'DATABASE_NOT_CONFIGURED';
      throw error;
    }
    pool = new Pool({ connectionString, max: 5, idleTimeoutMillis: 5000,
      connectionTimeoutMillis: 5000, statement_timeout: 10000 });
    pool.on('error', (error) => console.error('Idle database connection failed:', error.code));
    if (process.env.VERCEL) attachDatabasePool(pool);
  }
  return pool;
}

async function createSchema() {
  const client = await getPool().connect();
  try {
    await client.query('BEGIN');
    // Serialize schema creation across concurrent serverless cold starts.
    await client.query('SELECT pg_advisory_xact_lock(1987041201)');
    await client.query(`CREATE TABLE IF NOT EXISTS feedback (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      text TEXT NOT NULL,
      rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
      sentiment TEXT NOT NULL CHECK (sentiment IN ('positive', 'neutral', 'negative')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);
    await client.query('CREATE INDEX IF NOT EXISTS idx_created_at ON feedback(created_at)');
    await client.query('CREATE INDEX IF NOT EXISTS idx_sentiment ON feedback(sentiment)');
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    client.release();
  }
}

function initDb() {
  if (!initialization) {
    initialization = createSchema().catch((error) => {
      initialization = undefined;
      throw error;
    });
  }
  return initialization;
}

async function query(sql, parameters = []) {
  await initDb();
  return getPool().query(sql, parameters);
}

async function closeDb() {
  if (pool) await pool.end();
  pool = undefined;
  initialization = undefined;
}

module.exports = { initDb, query, closeDb };
